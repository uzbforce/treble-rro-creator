#!/usr/bin/env bash
# =============================================================================
# Module script generators
# =============================================================================
# Creates customize.sh and service.sh when src/module/ does not provide them.
# build.sh generates these from config.env by default; a file in src/module/
# is an advanced override and is packed as-is.
# =============================================================================

# ---------------------------------------------------------------------------
# service.sh — post-boot properties and overlay diagnostics
# ---------------------------------------------------------------------------
generate_service_sh() {
    local target="$1"

    cat > "$target/service.sh" << 'SERVEOF'
#!/sbin/sh
# =============================================================================
# Treble Overlay — Post-Boot Initialization
# =============================================================================
# Auto-generated by build.sh from config.env.
# Edit config.env and re-build; do not edit this file in the module.
#
# The overlay APKs are static RROs. Android loads and enables them during boot,
# before this script runs, so `cmd overlay enable` here is only a fallback and
# cannot change a static overlay. The loop below reports whether each APK was
# actually accepted, which is the fastest way to spot a wrong match property.
# =============================================================================

while [ "$(getprop sys.boot_completed)" != "1" ]; do
    sleep 5
done

PACKAGES="@OVERLAY_PACKAGE@ @OVERLAY_PACKAGE_SYSTEMUI@"

for pkg in $PACKAGES; do
    cmd overlay enable "$pkg" >/dev/null 2>&1 || true
    if cmd overlay list 2>/dev/null | grep -q "\[x\] $pkg"; then
        log -t treble-overlay "enabled: $pkg" 2>/dev/null || true
    else
        log -t treble-overlay "NOT enabled: $pkg (check the overlay match property and the module mount)" 2>/dev/null || true
    fi
done

SERVEOF

    # ── AOD / Doze ─────────────────────────────────────────────────────────
    if [ "$HAS_AOD" = "true" ]; then
        cat >> "$target/service.sh" << 'SERVEOF'
# ── AOD (PHH Treble Settings reads this property) ──────────────────────────
setprop persist.sys.overlay.aod true

SERVEOF
    fi

    # ── UDFPS ──────────────────────────────────────────────────────────────
    # The sensor geometry lives in the framework overlay resource
    # config_udfps_sensor_props. AOSP/TrebleDroid do not read persist.sys.udfps.*,
    # so no properties are written here.
    if [ "$HAS_UDFPS" = "true" ] && [ "$HAS_SAMSUNG_FINGERPRINT" = "true" ]; then
        cat >> "$target/service.sh" << 'SERVEOF'
# ── Samsung Goodix fingerprint workaround (PHH Treble Settings) ────────────
setprop persist.sys.phh.samsung_fingerprint 1

SERVEOF
    fi

    # ── Samsung FOD (fingerprint on display) ───────────────────────────────
    if [ "$HAS_SAMSUNG_FOD" = "true" ]; then
        cat >> "$target/service.sh" << 'SERVEOF'
# ── Samsung FOD: enable the touch panel's fingerprint area ─────────────────
TSP_SYS="/sys/class/sec/tsp/cmd"
if [ -f "$TSP_SYS" ]; then
    chmod 0660 "$TSP_SYS" 2>/dev/null || true
    if echo "fod_enable,1" > "$TSP_SYS" 2>/dev/null; then
        log -t treble-overlay "FOD enabled via $TSP_SYS" 2>/dev/null || true
    else
        log -t treble-overlay "FOD enable failed (SELinux?)" 2>/dev/null || true
    fi
fi

SERVEOF
    fi

    # ── Samsung vibrator HAL ───────────────────────────────────────────────
    if [ "$HAS_SAMSUNG_VIBRATOR" = "true" ]; then
        cat >> "$target/service.sh" << 'SERVEOF'
# ── Samsung vibrator service (started by vendor init on stock ROMs) ────────
VIB_SERVICE="sec-vibrator-2-2"
if [ -n "$(getprop init.svc.$VIB_SERVICE 2>/dev/null)" ]; then
    if [ "$(getprop init.svc.$VIB_SERVICE)" != "running" ]; then
        start "$VIB_SERVICE" 2>/dev/null || true
        sleep 1
        [ "$(getprop init.svc.$VIB_SERVICE)" = "running" ] \
            && log -t treble-overlay "vibrator HAL started" 2>/dev/null || true
    fi
fi

SERVEOF
    fi

    # ── Qualcomm/Samsung fingerprint nodes ─────────────────────────────────
    if [ "$HAS_UDFPS" = "true" ]; then
        cat >> "$target/service.sh" << 'SERVEOF'
# ── Fingerprint device-node permissions ────────────────────────────────────
# Normally done by vendor init scripts; GSIs may not run them.
if [ -e "/dev/esfp0" ]; then
    chmod 0660 /dev/esfp0 2>/dev/null || true
    chown system system /dev/esfp0 2>/dev/null || true
fi
if [ -e "/dev/goodix_fp" ]; then
    chmod 0660 /dev/goodix_fp 2>/dev/null || true
    chown system system /dev/goodix_fp 2>/dev/null || true
fi

for dir in /data/vendor/misc /data/vendor/misc/qti_fp /data/vendor/misc/qti_fp/template \
           /data/vendor/biometrics /data/vendor/fpSnrTest; do
    [ -d "$dir" ] && chmod 0770 "$dir" 2>/dev/null || true
done

SERVEOF
    fi

    # ── Vendor HAL services ────────────────────────────────────────────────
    if [ "$HAS_VENDOR_FINGERPRINT_HAL" = "true" ] || [ "$HAS_VENDOR_VIBRATOR_HAL" = "true" ]; then
        cat >> "$target/service.sh" << 'SERVEOF'
# ── Vendor HAL services ────────────────────────────────────────────────────
# Service names are defined by the .rc files in src/vendor/etc/init/.
SERVEOF

        if [ "$HAS_VENDOR_FINGERPRINT_HAL" = "true" ]; then
            cat >> "$target/service.sh" << 'SERVEOF'
for fp_hal in /vendor/bin/hw/android.hardware.biometrics.fingerprint*; do
    [ -f "$fp_hal" ] || continue
    for svc in vendor.fps_hal_aosp vendor.fps_hal vendor.fingerprint; do
        start "$svc" 2>/dev/null && break || true
    done
    break
done

SERVEOF
        fi

        if [ "$HAS_VENDOR_VIBRATOR_HAL" = "true" ]; then
            cat >> "$target/service.sh" << 'SERVEOF'
for vib_hal in /vendor/bin/hw/*vibrat*; do
    [ -f "$vib_hal" ] || continue
    for svc in sec-vibrator-2-2 vendor.vibrator vibrator; do
        start "$svc" 2>/dev/null && break || true
    done
    break
done

SERVEOF
        fi
    fi

    # ── Connectivity ───────────────────────────────────────────────────────
    if [ "$HAS_5G" = "true" ]; then
        cat >> "$target/service.sh" << 'SERVEOF'
# ── 5G (PHH Treble Settings) ───────────────────────────────────────────────
setprop persist.sys.phh.force_display_5g 1

SERVEOF
    fi

    if [ "$HAS_VOLTE" = "true" ]; then
        cat >> "$target/service.sh" << 'SERVEOF'
# ── VoLTE availability override (IMS still has to work for calls) ──────────
setprop persist.dbg.volte_avail_ovr 1

SERVEOF
    fi

    cat >> "$target/service.sh" << 'SERVEOF'
# ── Done ───────────────────────────────────────────────────────────────────
log -t treble-overlay "treble overlay service finished" 2>/dev/null || true

SERVEOF

    chmod +x "$target/service.sh"
    info "service.sh generated from config.env"
}

# ---------------------------------------------------------------------------
# post-fs-data.sh — set the overlay match property before zygote starts
# ---------------------------------------------------------------------------
# Static overlays that target "android" are matched by zygote while it preloads
# framework resources. Matching on ro.product.* is unreliable on GSI setups
# because some property areas are unreadable from the zygote domain, so the
# condition reads as empty and the overlay is enabled by the system server but
# never applied. persist.sys.* is readable everywhere and is set here before
# zygote starts.
# ---------------------------------------------------------------------------
generate_post_fs_data_sh() {
    local target="$1"

    cat > "$target/post-fs-data.sh" << 'PFSEOF'
#!/sbin/sh
# =============================================================================
# Treble Overlay — Match Property (runs before zygote)
# =============================================================================
# Auto-generated by build.sh from config.env.
#
# The static overlay APKs declare a required property, and Android evaluates it
# while zygote preloads framework resources. This script sets that property on
# every boot before zygote starts, so the condition always matches.
# =============================================================================

if [ "$(getprop @MATCH_PROP@)" != "@MATCH_VALUE@" ]; then
    setprop @MATCH_PROP@ "@MATCH_VALUE@"
fi

PFSEOF

    chmod +x "$target/post-fs-data.sh"
    info "post-fs-data.sh generated (match property)"
}

# ---------------------------------------------------------------------------
# customize.sh — installation permissions
# ---------------------------------------------------------------------------
generate_customize_sh() {
    local target="$1"
    cat > "$target/customize.sh" << 'CUSTOMIZE_EOF'
#!/sbin/sh
# =============================================================================
# Treble Overlay — KSU/Magisk Module Install Script
# =============================================================================
# Auto-generated by build.sh from src/vendor/ contents.
# For full control, use src/module/customize.sh instead.
# =============================================================================

# MODPATH is exported by the manager when it sources this script; fall back to
# the script location (some managers run it as `sh customize.sh`, where $0 is
# not a path).
MODPATH=${MODPATH:-${0%/*}}
[ -d "$MODPATH/system" ] || MODPATH="."

ui_print "  Installing ${MODPATH##*/}..."

# ── Overlay APKs ──────────────────────────────────────────────────────────
set_perm_recursive $MODPATH/system/product/overlay 0 0 0644 u:object_r:system_file:s0

CUSTOMIZE_EOF

    # Vendor HAL binaries
    if [ -d "$VENDOR_SRC_REL/bin/hw" ] && [ "$(ls -A "$VENDOR_SRC_REL"/bin/hw/ 2>/dev/null | grep -c .)" -gt 0 ]; then
        cat >> "$target/customize.sh" << 'CUSTOMIZE_BIN'

# ── Vendor HAL binaries ───────────────────────────────────────────────────
CUSTOMIZE_BIN
        for f in "$VENDOR_SRC_REL"/bin/hw/*; do
            [ -f "$f" ] || continue
            local name
            name=$(basename "$f")
            cat >> "$target/customize.sh" << CUSTOMIZE_BIN_ITEM
if [ -f "\$MODPATH/system/vendor/bin/hw/$name" ]; then
    set_perm "\$MODPATH/system/vendor/bin/hw/$name" 0 2000 0755 u:object_r:vendor_file:s0
    ui_print "  • HAL: $name"
fi

CUSTOMIZE_BIN_ITEM
        done
    fi

    # Shared libraries
    if [ -d "$VENDOR_SRC_REL/lib64" ] && [ "$(ls -A "$VENDOR_SRC_REL"/lib64/ 2>/dev/null | grep -c .)" -gt 0 ]; then
        cat >> "$target/customize.sh" << 'CUSTOMIZE_LIB'

# ── Shared libraries ──────────────────────────────────────────────────────
if [ -d "$MODPATH/system/vendor/lib64" ]; then
    set_perm_recursive $MODPATH/system/vendor/lib64 0 0 0644 u:object_r:vendor_file:s0
    ui_print "  • Vendor shared libraries set"
fi

CUSTOMIZE_LIB
    fi

    # Init .rc files
    if [ -d "$VENDOR_SRC_REL/etc/init" ] && [ "$(ls -A "$VENDOR_SRC_REL"/etc/init/ 2>/dev/null | grep -c .)" -gt 0 ]; then
        cat >> "$target/customize.sh" << 'CUSTOMIZE_RC'

# ── Init .rc files ────────────────────────────────────────────────────────
if [ -d "$MODPATH/system/vendor/etc/init" ]; then
    for rc in $MODPATH/system/vendor/etc/init/*.rc; do
        [ -f "$rc" ] && set_perm "$rc" 0 0 0644 u:object_r:vendor_configs_file:s0
    done
    ui_print "  • Init .rc files set ($(ls $MODPATH/system/vendor/etc/init/*.rc 2>/dev/null | wc -l) files)"
fi

CUSTOMIZE_RC
    fi

    # VINTF manifest fragments
    if [ -d "$VENDOR_SRC_REL/etc/vintf/manifest" ] && [ "$(ls -A "$VENDOR_SRC_REL"/etc/vintf/manifest/ 2>/dev/null | grep -c .)" -gt 0 ]; then
        cat >> "$target/customize.sh" << 'CUSTOMIZE_VINTF'

# ── VINTF manifest fragments ──────────────────────────────────────────────
if [ -d "$MODPATH/system/vendor/etc/vintf/manifest" ]; then
    for xml in $MODPATH/system/vendor/etc/vintf/manifest/*.xml; do
        [ -f "$xml" ] && set_perm "$xml" 0 0 0644 u:object_r:vendor_configs_file:s0
    done
    ui_print "  • VINTF manifest files set ($(ls $MODPATH/system/vendor/etc/vintf/manifest/*.xml 2>/dev/null | wc -l) files)"
fi

CUSTOMIZE_VINTF
    fi

    cat >> "$target/customize.sh" << 'CUSTOMIZE_END'

# ── Done ──────────────────────────────────────────────────────────────────
ui_print "  ✓ Module installed successfully!"
CUSTOMIZE_END

    chmod +x "$target/customize.sh"
}
