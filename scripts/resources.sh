#!/usr/bin/env bash
# =============================================================================
# Resource XML generators
# =============================================================================
# Applies config.env values to the overlay resources:
#   src/framework/res/values/generated.xml
#   src/framework/res/values-land/generated.xml
#   src/systemui/res/values/generated.xml
#
# Sourced by scripts/build.sh (common.sh loaded, config.env already sourced).
#
# Only resources that exist in AOSP (Android 13 through 16) are emitted.
# A resource name that the target does not have is a silent no-op at runtime,
# so build.sh audits the generated names against framework-res.apk afterwards.
# =============================================================================

# bc is not installed by default on Windows or in minimal Termux — use awk.
div255() {
    awk -v n="$1" 'BEGIN { printf "%.8f", n / 255 }'
}

# ---------------------------------------------------------------------------
# Validation helpers
# ---------------------------------------------------------------------------
is_uint() {
    [[ "$1" =~ ^[0-9]+$ ]]
}

is_number() {
    [[ "$1" =~ ^[0-9]+([.][0-9]+)?$ ]]
}

# xml_escape <text>  -> prints text safe for an XML string value.
xml_escape() {
    printf '%s' "$1" | sed 's/&/\&amp;/g; s/</\&lt;/g; s/>/\&gt;/g; s/"/\&quot;/g'
}

# normalize_size <value>  -> sets SIZE_VALUE and SIZE_UNIT (px or dp).
# Accepts "200", "200px", "24dp"; rejects everything else.
normalize_size() {
    local raw="$1" num unit
    raw=$(printf '%s' "$raw" | tr -d '[:space:]')
    if [[ "$raw" =~ ^([0-9]+([.][0-9]+)?)(px|dp)?$ ]]; then
        num="${BASH_REMATCH[1]}"
        unit="${BASH_REMATCH[3]:-px}"
        SIZE_VALUE="$num"
        SIZE_UNIT="$unit"
        return 0
    fi
    return 1
}

size_xml() {
    printf '%s%s' "$SIZE_VALUE" "$SIZE_UNIT"
}

# list_ints <space-separated>  -> true when every entry is an integer.
list_ints() {
    local v
    for v in $1; do
        is_uint "$v" || return 1
    done
    return 0
}

list_numbers() {
    local v
    for v in $1; do
        is_number "$v" || return 1
    done
    return 0
}

list_count() {
    local n=0 v
    for v in $1; do
        n=$((n + 1))
    done
    printf '%s' "$n"
}

# list_nondecreasing <space-separated numbers>
list_nondecreasing() {
    local prev="" v
    for v in $1; do
        if [ -n "$prev" ]; then
            awk -v a="$prev" -v b="$v" 'BEGIN { exit !(b >= a) }' || return 1
        fi
        prev="$v"
    done
    return 0
}

# emit_items <indent> <space-separated values>  -> writes <item> lines.
emit_items() {
    local indent="$1" values="$2" v
    for v in $values; do
        printf '%s<item>%s</item>\n' "$indent" "$v"
    done
}

# emit_brightness_key <config var> <resource name> [<float resource>]
# Appends the integer and (when AOSP has one) the matching 0.0-1.0 float dimen.
# Uses $gen from the calling generator.
emit_brightness_key() {
    local var="$1" res="$2" floatres="${3:-}" val="${!1}"
    [ -n "$val" ] || return 0
    [[ "$val" == *"<"* ]] && return 0
    if ! is_uint "$val" || [ "$val" -gt 255 ]; then
        warn "${var} must be an integer 0-255 — skipped"
        return 0
    fi
    printf '    <integer name="%s">%s</integer>\n' "$res" "$val" >> "$gen"
    if [ -n "$floatres" ]; then
        printf '    <item name="%s" format="float" type="dimen">%s</item>\n' \
            "$floatres" "$(div255 "$val")" >> "$gen"
    fi
    return 0
}

# ---------------------------------------------------------------------------
# Framework resource auto-generator
# ---------------------------------------------------------------------------
generate_resource_xml() {
    local gen="${RES_DIR}/values/generated.xml"
    local land_gen="${RES_DIR}/values-land/generated.xml"
    mkdir -p "${RES_DIR}/values" "${RES_DIR}/values-land"

    cat > "$gen" << 'GENEOF'
<?xml version="1.0" encoding="utf-8"?>
<!--
    Auto-generated by build.sh from config.env - DO NOT EDIT BY HAND.
    Edit config.env and re-build.

    The status bar block below writes status_bar_height_default because
    Android 12L+ (and therefore Android 13, 14, 15 and 16) calculates the
    status bar height from status_bar_height_default plus the display cutout.
    status_bar_height is kept as a compatibility value for apps that look the
    resource up by name. See docs/configuration.md#status-bar-height.
-->
<resources>

GENEOF

    # ── Feature flags (bools) ────────────────────────────────────────────
    if [ "$HAS_UDFPS" = "true" ]; then
        # AOSP has no config_supportsUdfps resource (that one is a custom-ROM
        # addition). The fingerprint sensor is registered through
        # config_biometric_sensors; the geometry is optional.
        if [ -n "${CONFIG_BIOMETRIC_SENSORS}" ] && [[ "${CONFIG_BIOMETRIC_SENSORS}" != *"<"* ]]; then
            local sensors_valid=true s
            IFS=';' read -ra sensors <<< "${CONFIG_BIOMETRIC_SENSORS}"
            for s in "${sensors[@]}"; do
                s=$(printf '%s' "$s" | xargs)
                [ -z "$s" ] && continue
                [[ "$s" =~ ^[0-9]+:[0-9]+:[0-9]+$ ]] || sensors_valid=false
            done
            if $sensors_valid; then
                cat >> "$gen" << GENEOF
    <string-array name="config_biometric_sensors">
$(IFS=';'; for s in "${sensors[@]}"; do s=$(printf '%s' "$s" | xargs); [ -n "$s" ] && printf '        <item>%s</item>\n' "$s"; done)
    </string-array>

GENEOF
            else
                warn "CONFIG_BIOMETRIC_SENSORS must be id:modality:strength entries (e.g. 0:2:15) — skipped"
            fi
        else
            # Default for a UDFPS: sensor 0, fingerprint modality, strong.
            cat >> "$gen" << 'GENEOF'
    <string-array name="config_biometric_sensors">
        <item>0:2:15</item>
    </string-array>

GENEOF
        fi

        # config_udfps_sensor_props is an integer-array of exactly three
        # values. Never write empty <item/> elements: Resources.getIntArray()
        # throws on them and SystemUI's biometrics code breaks.
        if is_uint "${UDFPS_X:-}" && is_uint "${UDFPS_Y:-}" && is_uint "${UDFPS_RADIUS:-}" \
           && [ "${UDFPS_RADIUS:-0}" -gt 0 ]; then
            cat >> "$gen" << GENEOF
    <integer-array name="config_udfps_sensor_props">
        <item>${UDFPS_X}</item>
        <item>${UDFPS_Y}</item>
        <item>${UDFPS_RADIUS}</item>
    </integer-array>

GENEOF
        else
            warn "HAS_UDFPS=true but UDFPS_X/UDFPS_Y/UDFPS_RADIUS are incomplete —"
            warn "  leaving config_udfps_sensor_props at the GSI default (the HAL/SystemUI will locate the sensor)"
        fi
    fi

    if [ "$HAS_AOD" = "true" ]; then
        cat >> "$gen" << GENEOF
    <bool name="config_dozeAlwaysOnDisplayAvailable">true</bool>

GENEOF
    fi

    if [ "$HAS_DOZE" = "true" ]; then
        cat >> "$gen" << GENEOF
    <bool name="config_dozeAfterScreenOffByDefault">true</bool>
    <bool name="config_dozePulsePickup">true</bool>

GENEOF
    fi

    if [ "$HAS_AUTO_BRIGHTNESS" = "true" ]; then
        cat >> "$gen" << GENEOF
    <bool name="config_automatic_brightness_available">true</bool>

GENEOF
    fi

    if [ "$HAS_BURN_IN_PROTECTION" = "true" ]; then
        # config_enableBurnInProtection is the AOSP switch used by SystemUI.
        # config_statusBarBurnInProtection is a Lineage/custom-ROM resource
        # that does not exist on a GSI, so it is not emitted.
        cat >> "$gen" << GENEOF
    <bool name="config_enableBurnInProtection">true</bool>

GENEOF
    fi

    if [ "$HAS_DOUBLE_TAP_WAKE" = "true" ]; then
        cat >> "$gen" << GENEOF
    <bool name="config_supportDoubleTapWake">true</bool>

GENEOF
    fi

    # HAS_HBM used to generate config_screenBrightnessExtendedMaximum and
    # config_dynamic_automatic_brightness_available. Neither exists in AOSP.
    # High-brightness mode is implemented by the panel/vendor driver.
    if [ "$HAS_HBM" = "true" ]; then
        warn "HAS_HBM is ignored: AOSP has no overlay resource for HBM (it is vendor/panel specific)"
    fi

    if [ "$HAS_5G" = "true" ]; then
        cat >> "$gen" << GENEOF
    <bool name="config_telephony5gNonStandalone">true</bool>

GENEOF
    fi

    if [ "$HAS_VOLTE" = "true" ]; then
        cat >> "$gen" << GENEOF
    <bool name="config_device_volte_available">true</bool>
    <bool name="config_device_vt_available">true</bool>
    <bool name="config_device_wfc_ims_available">true</bool>

GENEOF
    fi

    # ── Corner radius (dimen) — optional, skip if not set ────────────────
    if [ -n "${ROUNDED_CORNER_RADIUS:-}" ] && [[ "${ROUNDED_CORNER_RADIUS}" != *"<"* ]]; then
        if normalize_size "$ROUNDED_CORNER_RADIUS"; then
            local corner
            corner=$(size_xml)
            cat >> "$gen" << GENEOF
    <dimen name="rounded_corner_radius">${corner}</dimen>
    <dimen name="rounded_corner_radius_top">${corner}</dimen>
    <dimen name="rounded_corner_radius_bottom">${corner}</dimen>
    <dimen name="secondary_rounded_corner_radius">${corner}</dimen>
    <dimen name="secondary_rounded_corner_radius_top">${corner}</dimen>
    <dimen name="secondary_rounded_corner_radius_bottom">${corner}</dimen>

GENEOF
            # rounded_corner_content_padding is written only by the block below,
            # and only when STATUS_BAR_CONTENT_PADDING is set. Writing an implicit
            # 0px here would drag the bar content into the corners on ROMs whose
            # SystemUI does apply the framework value.
        else
            err "ROUNDED_CORNER_RADIUS must be a number in px or dp (e.g. 100 or 48dp), got: ${ROUNDED_CORNER_RADIUS}"
            exit 1
        fi
    fi

    # ── Status bar content padding (dimen: left / right inset) ──────────
    # AOSP 12L+ SystemUI has two candidate paths for the horizontal inset of
    # the status bar content, and which one is live depends on the ROM:
    #
    #   1. rounded_corner_content_padding (framework, this block)
    #        left  = max(value, display-cutout left inset)
    #        right = max(value, privacy-dot reserve)
    #      applied by StatusBarContentInsetsProvider -> PhoneStatusBarView.
    #   2. status_bar_padding_start/end (SystemUI, see the SystemUI block)
    #      plain XML padding of @+id/status_bar_contents, applied at inflate.
    #
    # Measured on an Android 16 GSI: path 1 was never applied (contents kept
    # their XML padding), while path 2 moved the content 1:1. Set both to the
    # same value so the inset lands whichever path the ROM uses; they do not
    # add up, because path 1 overrides the padding instead of adding to it.
    if [ -n "${STATUS_BAR_CONTENT_PADDING:-}" ] && [[ "${STATUS_BAR_CONTENT_PADDING}" != *"<"* ]]; then
        if normalize_size "$STATUS_BAR_CONTENT_PADDING"; then
            cat >> "$gen" << GENEOF
    <dimen name="rounded_corner_content_padding">$(size_xml)</dimen>

GENEOF
        else
            err "STATUS_BAR_CONTENT_PADDING must be a number in px or dp (e.g. 56 or 20dp), got: ${STATUS_BAR_CONTENT_PADDING}"
            exit 1
        fi
    fi

    # ── Status bar height (dimen) ────────────────────────────────────────
    # Android 12L changed SystemBarUtils to read status_bar_height_default.
    # Stock overlays therefore set:
    #   values/      status_bar_height_default = <portrait px>
    #                status_bar_height / _portrait (compatibility)
    #   values-land/ status_bar_height_default = <landscape>
    # quick_qs_offset_height keeps the QS header aligned with the bar.
    if [ -n "${STATUS_BAR_HEIGHT:-}" ] && [[ "${STATUS_BAR_HEIGHT}" != *"<"* ]]; then
        if ! normalize_size "$STATUS_BAR_HEIGHT"; then
            err "STATUS_BAR_HEIGHT must be a number in px or dp (e.g. 200 or 88px), got: ${STATUS_BAR_HEIGHT}"
            exit 1
        fi
        local sb_portrait
        sb_portrait=$(size_xml)

        local sb_land_raw="${STATUS_BAR_HEIGHT_LANDSCAPE:-24}"
        if ! normalize_size "$sb_land_raw"; then
            err "STATUS_BAR_HEIGHT_LANDSCAPE must be a number in px or dp, got: ${sb_land_raw}"
            exit 1
        fi
        local sb_landscape
        sb_landscape=$(size_xml)

        cat >> "$gen" << GENEOF
    <dimen name="status_bar_height_default">${sb_portrait}</dimen>
    <dimen name="status_bar_height">${sb_portrait}</dimen>
    <dimen name="status_bar_height_portrait">${sb_portrait}</dimen>
    <dimen name="status_bar_height_landscape">${sb_landscape}</dimen>
    <dimen name="quick_qs_offset_height">${sb_portrait}</dimen>

GENEOF

        cat > "$land_gen" << GENEOF
<?xml version="1.0" encoding="utf-8"?>
<!-- Auto-generated by build.sh from config.env - DO NOT EDIT BY HAND. -->
<resources>
    <dimen name="status_bar_height_default">${sb_landscape}</dimen>
    <dimen name="status_bar_height">${sb_landscape}</dimen>
    <dimen name="quick_qs_offset_height">${sb_landscape}</dimen>
</resources>
GENEOF

        # The framework takes max(status_bar_height_default, cutout safe
        # inset). A cutout taller than the configured bar wins; warn once.
        if [ -n "${DISPLAY_CUTOUT:-}" ]; then
            info "Status bar height is max(${sb_portrait}, display-cutout safe inset)"
        fi
    else
        # Never leave a stale landscape file from a previous build.
        rm -f "$land_gen"
    fi

    # ── Light sensor type (string) — optional, skip if not set ──────────
    if [ -n "${LIGHT_SENSOR_TYPE:-}" ] && [[ "${LIGHT_SENSOR_TYPE}" != *"<"* ]]; then
        local safe_sensor_type
        safe_sensor_type=$(xml_escape "$LIGHT_SENSOR_TYPE")
        cat >> "$gen" << GENEOF
    <string name="config_displayLightSensorType" translatable="false">${safe_sensor_type}</string>

GENEOF
    fi

    # ── Brightness (integers + float items) ───────────────────────────────
    # Each key is independent: only what you set is generated. Nothing is
    # filled in with a guessed default, because overriding
    # config_screenBrightnessSettingMaximum with 255 on a GSI that raised it
    # would cap the maximum brightness.
    # config_screenBrightnessDarkFloat does not exist in AOSP.
    emit_brightness_key "BRIGHTNESS_DIM"     "config_screenBrightnessDim"                 "config_screenBrightnessDimFloat"
    emit_brightness_key "BRIGHTNESS_DARK"    "config_screenBrightnessDark"                ""
    emit_brightness_key "BRIGHTNESS_DOZE"    "config_screenBrightnessDoze"                "config_screenBrightnessDozeFloat"
    emit_brightness_key "BRIGHTNESS_MIN"     "config_screenBrightnessSettingMinimum"      "config_screenBrightnessSettingMinimumFloat"
    emit_brightness_key "BRIGHTNESS_DEFAULT" "config_screenBrightnessSettingDefault"      "config_screenBrightnessSettingDefaultFloat"
    emit_brightness_key "BRIGHTNESS_MAX"     "config_screenBrightnessSettingMaximum"      "config_screenBrightnessSettingMaximumFloat"
    echo "" >> "$gen"

    # ── Display Cutout (string) ──────────────────────────────────────────
    if [ -n "${DISPLAY_CUTOUT:-}" ] && [[ "${DISPLAY_CUTOUT}" != *"<"* ]]; then
        local safe_cutout
        safe_cutout=$(xml_escape "$DISPLAY_CUTOUT")
        cat >> "$gen" << GENEOF
    <string name="config_mainBuiltInDisplayCutout" translatable="false">${safe_cutout}</string>

GENEOF
    fi

    # ── Optional Stock Bools (config.env OPTIONAL STOCK VALUES) ────────────
    # These are extracted from the user's stock product overlay APK.
    # They are commented out in config.env by default.
    for bool_var in \
        "CONFIG_FILL_MAIN_BUILTIN_DISPLAY_CUTOUT" \
        "CONFIG_POWER_DECOUPLE_INTERACTIVE_MODE_FROM_DISPLAY" \
        "CONFIG_POWER_DECOUPLE_AUTO_SUSPEND_MODE_FROM_DISPLAY" \
        "CONFIG_DISPLAY_BLANKS_AFTER_DOZE" \
        "CONFIG_DOZE_SUPPORTS_AOD_WALLPAPER" \
        "CONFIG_SUPPORT_AUDIO_SOURCE_UNPROCESSED" \
        "CONFIG_CAMERA_SOUND_FORCED" \
        "CONFIG_USE_DEV_INPUT_EVENT_FOR_AUDIO_JACK" \
        "CONFIG_WIFI_DISPLAY_SUPPORTS_PROTECTED_BUFFERS" \
        "CONFIG_CARRIER_VOLTE_AVAILABLE" \
        "CONFIG_CARRIER_VT_AVAILABLE" \
        "CONFIG_CARRIER_WFC_IMS_AVAILABLE" \
        "CONFIG_CARRIER_VOLTE_TTY_SUPPORTED" \
        "CONFIG_CAMERA_DOUBLE_TAP_POWER_GESTURE_ENABLED" \
        "SKIP_RESTORING_NETWORK_SELECTION" \
        "CONFIG_SWITCH_PHONE_ON_VOICE_REG_STATE_CHANGE"; do
        # Get the value from the variable whose name is in $bool_var
        val="${!bool_var}"
        [ -n "$val" ] || continue
        [ "$val" = "<value>" ] && continue
        if [ "$val" != "true" ] && [ "$val" != "false" ]; then
            warn "${bool_var} must be true or false — skipped"
            continue
        fi
        # Convert the env-style name to the Android resource name
        case "$bool_var" in
            CONFIG_FILL_MAIN_BUILTIN_DISPLAY_CUTOUT)          res_name="config_fillMainBuiltInDisplayCutout" ;;
            CONFIG_POWER_DECOUPLE_INTERACTIVE_MODE_FROM_DISPLAY) res_name="config_powerDecoupleInteractiveModeFromDisplay" ;;
            CONFIG_POWER_DECOUPLE_AUTO_SUSPEND_MODE_FROM_DISPLAY) res_name="config_powerDecoupleAutoSuspendModeFromDisplay" ;;
            CONFIG_DISPLAY_BLANKS_AFTER_DOZE)                 res_name="config_displayBlanksAfterDoze" ;;
            CONFIG_DOZE_SUPPORTS_AOD_WALLPAPER)               res_name="config_dozeSupportsAodWallpaper" ;;
            CONFIG_SUPPORT_AUDIO_SOURCE_UNPROCESSED)           res_name="config_supportAudioSourceUnprocessed" ;;
            CONFIG_CAMERA_SOUND_FORCED)                       res_name="config_camera_sound_forced" ;;
            CONFIG_USE_DEV_INPUT_EVENT_FOR_AUDIO_JACK)        res_name="config_useDevInputEventForAudioJack" ;;
            CONFIG_WIFI_DISPLAY_SUPPORTS_PROTECTED_BUFFERS)    res_name="config_wifiDisplaySupportsProtectedBuffers" ;;
            CONFIG_CARRIER_VOLTE_AVAILABLE)                   res_name="config_carrier_volte_available" ;;
            CONFIG_CARRIER_VT_AVAILABLE)                      res_name="config_carrier_vt_available" ;;
            CONFIG_CARRIER_WFC_IMS_AVAILABLE)                 res_name="config_carrier_wfc_ims_available" ;;
            CONFIG_CARRIER_VOLTE_TTY_SUPPORTED)               res_name="config_carrier_volte_tty_supported" ;;
            CONFIG_CAMERA_DOUBLE_TAP_POWER_GESTURE_ENABLED)   res_name="config_cameraDoubleTapPowerGestureEnabled" ;;
            SKIP_RESTORING_NETWORK_SELECTION)                 res_name="skip_restoring_network_selection" ;;
            CONFIG_SWITCH_PHONE_ON_VOICE_REG_STATE_CHANGE)    res_name="config_switch_phone_on_voice_reg_state_change" ;;
            *)                                                res_name="" ;;
        esac
        if [ -n "$res_name" ]; then
            cat >> "$gen" << GENEOF
    <bool name="${res_name}">${val}</bool>

GENEOF
        fi
    done

    # ── Optional Stock Strings ─────────────────────────────────────────────
    if [ -n "${CONFIG_RADIO_ACCESS_FAMILY:-}" ] && [[ "${CONFIG_RADIO_ACCESS_FAMILY}" != *"<"* ]]; then
        local safe_radio
        safe_radio=$(xml_escape "${CONFIG_RADIO_ACCESS_FAMILY}")
        cat >> "$gen" << GENEOF
    <string name="config_radio_access_family" translatable="false">${safe_radio}</string>

GENEOF
    fi

    if [ -n "${CONFIG_DOZE_UDFPS_LONG_PRESS_SENSOR_TYPE:-}" ] && [[ "${CONFIG_DOZE_UDFPS_LONG_PRESS_SENSOR_TYPE}" != *"<"* ]]; then
        local safe_udfps_type
        safe_udfps_type=$(xml_escape "${CONFIG_DOZE_UDFPS_LONG_PRESS_SENSOR_TYPE}")
        cat >> "$gen" << GENEOF
    <string name="config_dozeUdfpsLongPressSensorType" translatable="false">${safe_udfps_type}</string>

GENEOF
    fi

    # ── Auto-brightness Arrays ─────────────────────────────────────────────
    local auto_levels="${AUTO_BRIGHTNESS_LEVELS:-}"
    local auto_backlight="${AUTO_BRIGHTNESS_BACKLIGHT_VALUES:-}"
    local auto_nits="${AUTO_BRIGHTNESS_DISPLAY_VALUES_NITS:-}"
    local screen_nits="${SCREEN_BRIGHTNESS_NITS:-}"

    if [ -n "$auto_levels" ] && [[ "$auto_levels" != *"<"* ]]; then
        local levels_count backlight_count
        levels_count=$(list_count "$auto_levels")
        if ! list_ints "$auto_levels" || ! list_nondecreasing "$auto_levels"; then
            warn "AUTO_BRIGHTNESS_LEVELS must be non-decreasing integers — auto-brightness arrays skipped"
            auto_levels=""
        fi
    fi

    if [ -n "$auto_levels" ]; then
        local levels_count
        levels_count=$(list_count "$auto_levels")

        if [ -n "$auto_backlight" ] && [[ "$auto_backlight" != *"<"* ]]; then
            if ! list_ints "$auto_backlight" || ! list_nondecreasing "$auto_backlight"; then
                warn "AUTO_BRIGHTNESS_BACKLIGHT_VALUES must be non-decreasing integers — array skipped"
                auto_backlight=""
            elif [ "$(list_count "$auto_backlight")" -ne $((levels_count + 1)) ]; then
                warn "AUTO_BRIGHTNESS_BACKLIGHT_VALUES must have $(($levels_count + 1)) values (levels + 1),"
                warn "  got $(list_count "$auto_backlight") — array skipped"
                auto_backlight=""
            fi
        fi

        cat >> "$gen" << GENEOF
    <integer-array name="config_autoBrightnessLevels">
$(emit_items '        ' "$auto_levels")
    </integer-array>

GENEOF

        if [ -n "$auto_backlight" ]; then
            cat >> "$gen" << GENEOF
    <integer-array name="config_autoBrightnessLcdBacklightValues">
$(emit_items '        ' "$auto_backlight")
    </integer-array>

GENEOF
        fi

        # OLED devices use a nits curve instead of the 0-255 backlight.
        if [ -n "$auto_nits" ] && [[ "$auto_nits" != *"<"* ]]; then
            if ! list_numbers "$auto_nits" || ! list_nondecreasing "$auto_nits"; then
                warn "AUTO_BRIGHTNESS_DISPLAY_VALUES_NITS must be non-decreasing numbers — skipped"
            elif [ "$(list_count "$auto_nits")" -ne $((levels_count + 1)) ]; then
                warn "AUTO_BRIGHTNESS_DISPLAY_VALUES_NITS must have $(($levels_count + 1)) values, got $(list_count "$auto_nits") — skipped"
            else
                cat >> "$gen" << GENEOF
    <array name="config_autoBrightnessDisplayValuesNits">
$(emit_items '        ' "$auto_nits")
    </array>

GENEOF
            fi
        fi
    fi

    # config_screenBrightnessNits is indexed by config_screenBrightnessBacklight,
    # so both arrays must be present and the same length.
    local screen_backlight="${SCREEN_BRIGHTNESS_BACKLIGHT:-}"
    if [ -n "$screen_nits" ] && [[ "$screen_nits" != *"<"* ]]; then
        if [ -z "$screen_backlight" ] || [[ "$screen_backlight" == *"<"* ]]; then
            warn "SCREEN_BRIGHTNESS_NITS needs SCREEN_BRIGHTNESS_BACKLIGHT (same number of values) — skipped"
        elif ! list_ints "$screen_backlight" || ! list_nondecreasing "$screen_backlight"; then
            warn "SCREEN_BRIGHTNESS_BACKLIGHT must be non-decreasing integers — nits arrays skipped"
        elif ! list_numbers "$screen_nits" || ! list_nondecreasing "$screen_nits"; then
            warn "SCREEN_BRIGHTNESS_NITS must be non-decreasing numbers — skipped"
        elif [ "$(list_count "$screen_nits")" -ne "$(list_count "$screen_backlight")" ]; then
            warn "SCREEN_BRIGHTNESS_NITS and SCREEN_BRIGHTNESS_BACKLIGHT must have the same number of values — skipped"
        else
            cat >> "$gen" << GENEOF
    <integer-array name="config_screenBrightnessBacklight">
$(emit_items '        ' "$screen_backlight")
    </integer-array>

    <array name="config_screenBrightnessNits">
$(emit_items '        ' "$screen_nits")
    </array>

GENEOF
        fi
    fi

    # ── Refresh rate (integers) — optional, skip if not set ──────────────
    if [ -n "${DEFAULT_REFRESH_RATE:-}" ] && [[ "${DEFAULT_REFRESH_RATE}" != *"<"* ]]; then
        local rr_default="$DEFAULT_REFRESH_RATE"
        local rr_peak="${PEAK_REFRESH_RATE:-$DEFAULT_REFRESH_RATE}"
        if is_uint "$rr_default" && is_uint "$rr_peak" && [ "$rr_default" -gt 0 ] && [ "$rr_peak" -gt 0 ]; then
            cat >> "$gen" << GENEOF
    <integer name="config_defaultRefreshRate">${rr_default}</integer>
    <integer name="config_defaultPeakRefreshRate">${rr_peak}</integer>

GENEOF
        else
            warn "DEFAULT_REFRESH_RATE / PEAK_REFRESH_RATE must be positive integers — skipped"
        fi
    fi

    # Close resources
    echo "</resources>" >> "$gen"

    local val_count
    val_count=$(grep -cE '<(bool|dimen|integer|string|integer-array|array)[[:space:]]+name=' "$gen" 2>/dev/null || true)
    ok "Generated: ${RES_DIR}/values/generated.xml (${val_count:-0} resource entries from config.env)"
}

# ---------------------------------------------------------------------------
# SystemUI overlay resource generator
# ---------------------------------------------------------------------------
generate_systemui_resource_xml() {
    local gen="${SYSUI_RES_DIR}/values/generated.xml"
    mkdir -p "$(dirname "$gen")"

    local doze_state="false"
    local doze_suspend_state="true"
    [ "$HAS_AOD" = "true" ] && doze_state="true"
    [ "$DOZE_SUSPEND_UNSUPPORTED" = "true" ] && doze_suspend_state="false"

    # Only resources that exist in AOSP SystemUI 13-16.
    # doze_pickup_performs_proximity_check was removed from AOSP and is not
    # emitted (a missing target resource is silently ignored).
    cat > "$gen" << GENEOF
<?xml version="1.0" encoding="utf-8"?>
<!-- Auto-generated by build.sh from config.env - DO NOT EDIT BY HAND. -->
<resources>
    <bool name="doze_display_state_supported">${doze_state}</bool>
    <bool name="doze_suspend_display_state_supported">${doze_suspend_state}</bool>
    <bool name="doze_proximity_check_before_pulse">false</bool>
GENEOF

    # ── Privacy dot ───────────────────────────────────────────────────────
    # While the dot is enabled, SystemUI reserves ongoing_appops_dot_min_padding
    # on the end side of the status bar content (see
    # StatusBarContentInsetsProvider.getCalculatedAreaForRotation).
    if [ -n "${HAS_PRIVACY_DOT:-}" ] && [[ "${HAS_PRIVACY_DOT}" != *"<"* ]]; then
        printf '    <bool name="config_enablePrivacyDot">%s</bool>\n' "$HAS_PRIVACY_DOT" >> "$gen"
    fi

    # ── Status bar paddings ───────────────────────────────────────────────
    # Dimens read by SystemUI (Android 13-16):
    #   status_bar_padding_start/end/top   inner padding of the bar contents
    #                                      (PhoneStatusBarView.updatePaddings)
    #   status_bar_icons_padding_start/end padding of the system-icons cluster
    #                                      (clock/battery/signal side)
    #   ongoing_appops_dot_min_padding     end-side reserve for the privacy dot
    # They apply in addition to rounded_corner_content_padding (framework).
    sysui_size_entry() {  # <resource-name> <value> <config-key>
        local name="$1" value="$2" key="$3"
        [ -n "$value" ] || return 0
        [[ "$value" == *"<"* ]] && return 0
        if ! normalize_size "$value"; then
            err "${key} must be a number in px or dp (e.g. 64 or 24dp), got: ${value}"
            exit 1
        fi
        printf '    <dimen name="%s">%s</dimen>\n' "$name" "$(size_xml)" >> "$gen"
    }

    sysui_size_entry status_bar_padding_start       "${STATUS_BAR_PADDING_START:-}"       STATUS_BAR_PADDING_START
    sysui_size_entry status_bar_padding_end         "${STATUS_BAR_PADDING_END:-}"         STATUS_BAR_PADDING_END
    sysui_size_entry status_bar_padding_top         "${STATUS_BAR_PADDING_TOP:-}"         STATUS_BAR_PADDING_TOP
    sysui_size_entry status_bar_icons_padding_start "${STATUS_BAR_ICONS_PADDING_START:-}" STATUS_BAR_ICONS_PADDING_START
    sysui_size_entry status_bar_icons_padding_end   "${STATUS_BAR_ICONS_PADDING_END:-}"   STATUS_BAR_ICONS_PADDING_END
    sysui_size_entry ongoing_appops_dot_min_padding "${STATUS_BAR_DOT_MIN_PADDING:-}"     STATUS_BAR_DOT_MIN_PADDING

    echo "</resources>" >> "$gen"

    local sysui_count
    sysui_count=$(grep -cE '<(bool|dimen)[[:space:]]+name=' "$gen" 2>/dev/null || true)
    ok "Generated: ${SYSUI_RES_DIR}/values/generated.xml (${sysui_count:-0} resource entries)"
}
