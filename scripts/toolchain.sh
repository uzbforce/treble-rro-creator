#!/usr/bin/env bash
# =============================================================================
# Treble Overlay — toolchain installer and verifier
# =============================================================================
# Sourced by build.sh. Nothing here runs on its own.
#
#   ./build.sh            installs whatever is missing (sensible defaults)
#   ./build.sh setup      interactive installer (pick distro / resource version)
#   ./build.sh doctor     read-only check, exits 0 when a build would work
# =============================================================================

# ---------------------------------------------------------------------------
# Windows: Google build-tools zip
# ---------------------------------------------------------------------------
# Git for Windows ships bash and coreutils, but no aapt2/zipalign/apksigner.
# Google's Windows build-tools zip contains all three, so one download covers
# the whole toolchain.
install_windows_tools() {
    mkdir -p "$TOOLS_DIR"

    if ! command -v unzip >/dev/null 2>&1; then
        err "unzip not found — reinstall Git for Windows (it bundles unzip)"
        return 1
    fi
    if ! command -v curl >/dev/null 2>&1; then
        err "curl not found — reinstall Git for Windows (it bundles curl)"
        return 1
    fi
    if ! command -v java >/dev/null 2>&1; then
        err "Java not found — apksigner needs a JDK (17 or newer)."
        echo "      Install one: https://adoptium.net/"
        echo "      or:          winget install EclipseAdoptium.Temurin.17.JDK"
        echo "      Then re-run: build.cmd"
        return 1
    fi

    local tmp_zip="${TOOLS_DIR}/build-tools-win.zip"
    local api="" url=""

    info "Downloading Android build-tools for Windows..."
    for api in 36 35 34; do
        url="https://dl.google.com/android/repository/build-tools_r${api}_windows.zip"
        info "  Trying build-tools r${api}..."
        if curl --fail -L --retry 2 "$url" -o "$tmp_zip" 2>/dev/null; then
            break
        fi
        api=""
    done

    if [ -z "$api" ]; then
        err "Could not download the Windows build-tools."
        info "Install Android SDK build-tools and add its folder to PATH, or copy"
        info "aapt2.exe and zipalign.exe into tools/ and re-run build.cmd."
        rm -f "$tmp_zip"
        return 1
    fi

    rm -rf "${TOOLS_DIR}/build-tools-win"
    mkdir -p "${TOOLS_DIR}/build-tools-win"
    if ! unzip -q -o "$tmp_zip" -d "${TOOLS_DIR}/build-tools-win"; then
        err "Failed to extract the build-tools archive"
        rm -f "$tmp_zip"
        return 1
    fi
    rm -f "$tmp_zip"

    local bt_dir
    bt_dir=$(ls -d "${TOOLS_DIR}/build-tools-win/"* 2>/dev/null | head -1)
    if [ -z "$bt_dir" ]; then
        err "Unexpected build-tools archive layout"
        return 1
    fi
    ok "build-tools r${api} downloaded"

    local installed=false exe
    for exe in aapt2.exe zipalign.exe; do
        if [ -f "${bt_dir}/${exe}" ]; then
            cp "${bt_dir}/${exe}" "${TOOLS_DIR}/${exe}"
            ok "Installed ${exe}"
            installed=true
        else
            warn "${exe} not found in the build-tools package"
        fi
    done

    # A Linux aapt2/zipalign left in tools/ by a WSL/Kali run of this project
    # would shadow the .exe installed above and break the build with
    # "cannot execute binary file".
    local stale
    for stale in "${TOOLS_DIR}/aapt2" "${TOOLS_DIR}/zipalign"; do
        if [ -f "$stale" ] && [ "$(classify_binary "$stale")" = "linux-elf" ]; then
            rm -f "$stale"
            warn "Removed stale Linux binary ${stale#"${TOOLS_DIR}"/} (it shadowed the Windows one)"
        fi
    done

    # apksigner: bash does not resolve .bat files, so wrap the jar in a small
    # shell script — `apksigner ...` then behaves exactly like on Linux.
    if [ -f "${bt_dir}/lib/apksigner.jar" ]; then
        cp "${bt_dir}/lib/apksigner.jar" "${TOOLS_DIR}/apksigner.jar"
        cat > "${TOOLS_DIR}/apksigner" << 'APKSIGNER_EOF'
#!/bin/sh
# Generated by build.sh — runs the build-tools apksigner jar.
here=$(cd "$(dirname "$0")" && pwd)
case "$(uname -s 2>/dev/null)" in
    MINGW*|MSYS*|CYGWIN*) here=$(cygpath -w "$here") ;;
esac
exec java -jar "$here/apksigner.jar" "$@"
APKSIGNER_EOF
        chmod +x "${TOOLS_DIR}/apksigner"
        ok "Installed apksigner (java -jar tools/apksigner.jar)"
        installed=true
    else
        warn "apksigner.jar not found in the build-tools package"
    fi

    # Everything needed is copied into tools/; drop the ~120 MB extraction.
    rm -rf "${TOOLS_DIR}/build-tools-win"

    $installed
}

# ---------------------------------------------------------------------------
# Resource dictionary (framework-res.apk)
# ---------------------------------------------------------------------------
# aapt2 needs the platform resource table to resolve android:* IDs. Android 13
# is the most reliable version and links overlays for 13 through 16.
download_platform_resources() {
    local sdk_ver="$1"
    mkdir -p "$TOOLS_DIR"

    local tmp_zip="${TOOLS_DIR}/platform_tmp.zip"
    local rev url success=false

    info "Downloading Android ${sdk_ver} resources from Google..."
    # r02 is the known-good revision for API 33; try it first, then the rest.
    for rev in r02 r01 r03 r04 r05 r06 r07 r08 ""; do
        url="https://dl.google.com/android/repository/platform-${sdk_ver}_${rev}.zip"
        url="${url%_}" # strip trailing underscore when rev is empty
        if curl --fail -L "$url" -o "$tmp_zip" 2>/dev/null; then
            success=true
            break
        fi
    done

    if [ "$success" != "true" ]; then
        err "Download failed for all revisions — Google may have moved the files."
        rm -f "$tmp_zip"
        return 1
    fi

    info "Extracting android.jar (resource table)..."
    if ! unzip -j -o "$tmp_zip" "*/android.jar" -d "$TOOLS_DIR/" >/dev/null 2>&1; then
        err "Could not extract android.jar from the platform archive"
        rm -f "$tmp_zip"
        return 1
    fi
    if [ ! -f "$TOOLS_DIR/android.jar" ]; then
        err "The archive did not contain android.jar"
        rm -f "$tmp_zip"
        return 1
    fi

    mv "$TOOLS_DIR/android.jar" "$TOOLS_DIR/framework-res.apk"
    rm -f "$tmp_zip"
    ok "Android ${sdk_ver} resources installed (tools/framework-res.apk, $(du -sh "$TOOLS_DIR/framework-res.apk" | cut -f1))"
}

# acquire_framework_res <auto|ask> [force]
# `force` asks/downloads even when a resource dictionary already exists.
acquire_framework_res() {
    local mode="${1:-ask}" force="${2:-}"

    if [ -z "$force" ] && framework_res_path >/dev/null 2>&1; then
        return 0
    fi

    if [ "$mode" = "auto" ]; then
        download_platform_resources 33
        return $?
    fi

    echo ""
    info "One more piece: framework-res.apk (the resource dictionary)."
    echo "  aapt2 uses it to translate android:* resource IDs. Using the wrong"
    echo "  version causes 'resource not found' errors during the build."
    echo ""
    echo -e "  ${BOLD}Where should it come from?${NC}"
    echo -e "    ${BOLD}[1]${NC} Download Android 13 resources  (${GREEN}recommended${NC} — works for 13-16)"
    echo -e "    ${BOLD}[2]${NC} Download Android 14"
    echo -e "    ${BOLD}[3]${NC} Download Android 15"
    echo -e "    ${BOLD}[4]${NC} Download Android 16 (preview)"
    echo -e "    ${BOLD}[5]${NC} Pull from the connected device  (${RED}not recommended${NC})"
    echo "        Manufacturer builds are often stripped/odexed and aapt2 will fail."
    echo -e "    ${BOLD}[n]${NC} Skip for now"
    echo ""
    ask "  Choose [1/2/3/4/5/n]: " "1"

    case "$REPLY" in
        1|2|3|4)
            local sdk_ver="33"
            [ "$REPLY" = "2" ] && sdk_ver="34"
            [ "$REPLY" = "3" ] && sdk_ver="35"
            [ "$REPLY" = "4" ] && sdk_ver="36"
            download_platform_resources "$sdk_ver"
            ;;
        5)
            mkdir -p "$TOOLS_DIR"
            info "Trying to pull /system/framework/framework-res.apk..."
            if cp /system/framework/framework-res.apk "$TOOLS_DIR/framework-res.apk" 2>/dev/null; then
                ok "framework-res.apk pulled"
            elif command -v su >/dev/null 2>&1 && \
                 su -c "cp /system/framework/framework-res.apk \"$TOOLS_DIR/framework-res.apk\"" 2>/dev/null; then
                ok "framework-res.apk pulled (via su)"
            else
                err "Could not read /system/framework/framework-res.apk (this only works on Android/Termux)."
                info "Use one of the download options instead."
                return 1
            fi
            ;;
        *)
            info "Skipped — aapt2 will need framework-res.apk before it can link."
            return 1
            ;;
    esac
}

# ---------------------------------------------------------------------------
# Linux / Termux: package managers
# ---------------------------------------------------------------------------
# Prints the manual command for the detected distro (used by doctor and by
# error messages when an unattended install is not possible).
package_install_hint() {
    if $IS_TERMUX; then
        echo "pkg install -y aapt2 apksigner android-tools openjdk-17 unzip zip curl"
    elif command -v apt-get >/dev/null 2>&1; then
        echo "sudo apt install -y aapt android-sdk-build-tools apksigner android-framework-res zip curl"
    elif command -v pacman >/dev/null 2>&1; then
        echo "sudo pacman -S --needed android-tools jdk-openjdk zip curl"
    elif command -v dnf >/dev/null 2>&1; then
        echo "sudo dnf install -y android-tools java-17-openjdk zip curl"
    else
        echo "./build.sh setup   (choose 'Manual download')"
    fi
}

# install_linux_packages <auto|interactive>
install_linux_packages() {
    local mode="${1:-auto}"
    local sudo=""

    if $IS_TERMUX; then
        info "Termux detected — running: pkg install ..."
        if pkg install -y aapt2 apksigner android-tools openjdk-17 unzip zip curl tsu; then
            ok "Packages installed"
            return 0
        fi
        warn "Package installation failed (often a repository mirror problem)."
        echo "     Run: termux-change-repo   → pick a nearby mirror"
        echo "     Then: apt update && ./build.sh setup"
        return 1
    fi

    if command -v apt-get >/dev/null 2>&1; then
        if [ "$(id -u)" -ne 0 ]; then
            if [ "$mode" = "auto" ]; then
                # Never sit waiting for a password: only run unattended when
                # sudo is already available without one.
                if ! sudo -n true 2>/dev/null; then
                    warn "Root privileges are needed to install the build tools."
                    echo "     Run: $(package_install_hint)"
                    echo "     Then re-run: ./build.sh"
                    return 1
                fi
            fi
            sudo="sudo"
        fi
        info "Installing Debian/Ubuntu packages (apt)..."
        $sudo apt-get update && \
        $sudo apt-get install -y aapt android-sdk-build-tools apksigner android-framework-res zip curl
        return $?
    fi

    if command -v pacman >/dev/null 2>&1; then
        if [ "$(id -u)" -ne 0 ]; then
            if [ "$mode" = "auto" ] && ! sudo -n true 2>/dev/null; then
                warn "Root privileges are needed to install the build tools."
                echo "     Run: $(package_install_hint)"
                echo "     Then re-run: ./build.sh"
                return 1
            fi
            sudo="sudo"
        fi
        info "Installing Arch Linux packages (pacman)..."
        $sudo pacman -S --needed android-tools jdk-openjdk zip curl
        return $?
    fi

    if command -v dnf >/dev/null 2>&1; then
        if [ "$(id -u)" -ne 0 ]; then
            if [ "$mode" = "auto" ] && ! sudo -n true 2>/dev/null; then
                warn "Root privileges are needed to install the build tools."
                echo "     Run: $(package_install_hint)"
                echo "     Then re-run: ./build.sh"
                return 1
            fi
            sudo="sudo"
        fi
        info "Installing Fedora packages (dnf)..."
        $sudo dnf install -y android-tools java-17-openjdk zip curl
        return $?
    fi

    return 1
}

# ---------------------------------------------------------------------------
# Manual install into tools/ (no root)
# ---------------------------------------------------------------------------
download_manual_tools() {
    mkdir -p "$TOOLS_DIR"

    if ! command -v curl >/dev/null 2>&1; then
        err "curl not found — install curl and re-run"
        return 1
    fi

    # --- aapt2 -------------------------------------------------------------
    if ! tool_ready aapt2; then
        info "Downloading aapt2 from Google Maven..."
        local version
        version=$(curl -sL "https://dl.google.com/dl/android/maven2/com/android/tools/build/aapt2/maven-metadata.xml" \
            | grep -oP '<release>\K[^<]+' || true)
        if [ -z "$version" ]; then
            version="9.3.0-alpha07-15228143"
            info "Could not read the latest version, using ${version}"
        else
            ok "Latest aapt2 version: ${version}"
        fi

        local aapt2_os="linux"
        $IS_WINDOWS && aapt2_os="windows"
        local url="https://dl.google.com/dl/android/maven2/com/android/tools/build/aapt2/${version}/aapt2-${version}-${aapt2_os}.jar"
        local jar="${TMPDIR:-/tmp}/aapt2-download.jar"

        if ! curl -sL "$url" -o "$jar" || [ ! -s "$jar" ]; then
            err "Could not download aapt2"
            rm -f "$jar"
            return 1
        fi

        # The jar is a zip that also holds META-INF/ and NOTICE; extract only
        # the binary so tools/ stays clean. On Windows MSYS resolves the bare
        # name to the .exe, so drop both spellings first.
        rm -f "$TOOLS_DIR/aapt2" "$TOOLS_DIR/aapt2.exe"
        ( cd "$TOOLS_DIR" && { unzip -o "$jar" "aapt2.exe" || unzip -o "$jar" "aapt2"; } 2>/dev/null )
        chmod +x "$TOOLS_DIR/aapt2" 2>/dev/null || true
        rm -f "$jar"

        if tool_ready aapt2; then
            ok "aapt2 installed to tools/"
        else
            err "Could not extract aapt2 from the downloaded jar"
            return 1
        fi
    fi

    # --- zipalign / apksigner ---------------------------------------------
    if ! tool_ready zipalign || ! tool_ready apksigner; then
        if $IS_WINDOWS; then
            install_windows_tools || return 1
        elif ! command -v java >/dev/null 2>&1; then
            err "Java not found — it is needed for zipalign/apksigner and the resource table."
            echo "     Install: $(package_install_hint)"
            echo "     Then re-run: ./build.sh setup"
            return 1
        else
            info "zipalign/apksigner missing — using the Android command-line tools."
            if [ ! -d "$TOOLS_DIR/cmdline-tools" ]; then
                local tools_zip="${TMPDIR:-/tmp}/cmdline-tools.zip"
                if ! curl -sL "https://dl.google.com/android/repository/commandlinetools-linux-11076708_latest.zip" -o "$tools_zip"; then
                    err "Could not download the Android command-line tools"
                    rm -f "$tools_zip"
                    return 1
                fi
                unzip -q "$tools_zip" -d "$TOOLS_DIR/"
                rm -f "$tools_zip"
                ok "Android command-line tools downloaded"
            fi

            local sdkmanager="$TOOLS_DIR/cmdline-tools/bin/sdkmanager"
            if [ ! -f "$sdkmanager" ]; then
                err "sdkmanager not found after extraction"
                return 1
            fi

            echo "  Installing build-tools (the Android SDK license is accepted automatically)."
            yes | "$sdkmanager" --sdk_root="$TOOLS_DIR/android-sdk" "build-tools;35.0.0" >/dev/null 2>&1 || true
            yes | "$sdkmanager" --sdk_root="$TOOLS_DIR/android-sdk" "platforms;android-33" >/dev/null 2>&1 || true

            local bt_dir
            bt_dir=$(ls -d "$TOOLS_DIR/android-sdk/build-tools/"* 2>/dev/null | head -1)
            if [ -n "$bt_dir" ]; then
                local t
                for t in zipalign apksigner; do
                    [ -f "$bt_dir/$t" ] || continue
                    ln -sf "$bt_dir/$t" "$TOOLS_DIR/$t" 2>/dev/null || \
                        cp "$bt_dir/$t" "$TOOLS_DIR/" 2>/dev/null || true
                    chmod +x "$TOOLS_DIR/$t" 2>/dev/null || true
                done
                ok "zipalign and apksigner installed from build-tools"
            else
                warn "Build-tools installation failed."
                info "Try: ./build.sh setup   (or $(package_install_hint))"
                return 1
            fi

            if ! framework_res_path >/dev/null 2>&1; then
                local platform_dir
                platform_dir=$(ls -d "$TOOLS_DIR/android-sdk/platforms/"* 2>/dev/null | head -1)
                if [ -n "$platform_dir" ] && [ -f "$platform_dir/data/res/framework-res.apk" ]; then
                    cp "$platform_dir/data/res/framework-res.apk" "$TOOLS_DIR/"
                    ok "framework-res.apk taken from the platform SDK"
                fi
            fi
        fi
    fi

    return 0
}

# ---------------------------------------------------------------------------
# Doctor — verify the toolchain actually works on THIS platform
# ---------------------------------------------------------------------------
check_runs() {
    local label="$1"; shift
    local out rc=0
    out=$("$@" 2>&1) || rc=$?
    if printf '%s' "$out" | grep -qiE 'cannot execute binary file|exec format error|not a valid win32|bad cpu type'; then
        printf '    %-22s ✗ %s\n' "$label" "$(printf '%s' "$out" | head -1 | cut -c1-70)"
        return 1
    fi
    printf '    %-22s ✓ ran\n' "$label"
    if [ "$rc" -ne 0 ]; then
        printf '    %-22s   (exit %s — normal for tools without arguments)\n' "" "$rc"
    fi
    return 0
}

run_doctor() {
    local problems=0 t cand kind usable bad

    if $IS_WINDOWS; then
        banner "Toolchain check  (build.cmd doctor)"
    else
        banner "Toolchain check  (build.sh doctor)"
    fi
    echo -e "  ${BOLD}Environment${NC}"
    printf '    %-12s %s\n' "Shell:" "$(uname -s 2>/dev/null || echo unknown)  (MSYSTEM=${MSYSTEM:-unset})"
    if $IS_WINDOWS; then
        printf '    %-12s %s\n' "Platform:" "Windows (Git Bash / MSYS2)"
    elif $IS_TERMUX; then
        printf '    %-12s %s\n' "Platform:" "Android / Termux"
    elif $IS_WSL; then
        printf '    %-12s %s\n' "Platform:" "WSL (Linux)"
    else
        printf '    %-12s %s\n' "Platform:" "Linux"
    fi
    printf '    %-12s %s\n' "Project:" "$ROOT"
    printf '    %-12s %s\n' "Tools dir:" "$TOOLS_DIR"
    echo ""
    echo -e "  ${BOLD}Tools${NC}"

    for t in aapt2 zipalign apksigner; do
        usable=""; bad=""
        while IFS= read -r cand; do
            [ -n "$cand" ] || continue
            kind=$(classify_binary "$cand")
            if kind_usable "$kind"; then
                [ -z "$usable" ] && usable="$cand"
            else
                bad="${bad}${cand} [$(kind_label "$kind")] "
            fi
        done <<< "$(tool_candidates "$t")"

        if [ -n "$usable" ]; then
            printf '    %-12s ✓ %s  [%s]\n' "$t" "$usable" "$(kind_label "$(classify_binary "$usable")")"
            if [ -n "$bad" ]; then
                printf '    %-12s   ⚠ shadows it, cannot run here: %s\n' "" "$bad"
                problems=$((problems + 1))
            fi
        elif [ -n "$bad" ]; then
            printf '    %-12s ✗ only unusable copies: %s\n' "$t" "$bad"
            problems=$((problems + 1))
        else
            printf '    %-12s ✗ not found\n' "$t"
            problems=$((problems + 1))
        fi
    done

    local res
    if res=$(framework_res_path); then
        printf '    %-12s ✓ %s  [%s]\n' "resources" "$res" "$(kind_label "$(classify_binary "$res")")"
    else
        printf '    %-12s ✗ not found — build.sh will download it\n' "resources"
        problems=$((problems + 1))
    fi

    local jpath
    jpath=$(command -v java 2>/dev/null || true)
    if [ -n "$jpath" ]; then
        printf '    %-12s ✓ %s  [%s]\n' "java" "$jpath" "$(kind_label "$(classify_binary "$jpath")")"
    else
        printf '    %-12s ✗ not found — apksigner will fail\n' "java"
        problems=$((problems + 1))
    fi

    echo ""
    echo -e "  ${BOLD}Do they actually run here?${NC}"
    local rbin
    for t in aapt2 zipalign apksigner; do
        rbin=$(tool_path "$t") || continue
        case "$t" in
            aapt2)     check_runs "$t version" "$rbin" version || problems=$((problems + 1)) ;;
            zipalign)  check_runs "$t" "$rbin" || problems=$((problems + 1)) ;;
            apksigner) check_runs "$t --version" "$rbin" --version || problems=$((problems + 1)) ;;
        esac
    done

    echo ""
    echo -e "  ${BOLD}Contamination check${NC}"
    local found_foreign=false f fkind
    for f in "$TOOLS_DIR"/*; do
        [ -f "$f" ] || continue
        fkind=$(classify_binary "$f")
        if kind_foreign "$fkind"; then
            printf '    ⚠ %s is a %s — cannot run here\n' "${f#"$TOOLS_DIR"/}" "$(kind_label "$fkind")"
            printf '      remove it:  rm -f "%s"\n' "$f"
            found_foreign=true
        fi
    done
    while IFS= read -r cand; do
        case "$cand" in
            //wsl\$/*|*wsl.localhost*)
                printf '    ⚠ PATH contains a WSL path: %s\n' "$cand"
                found_foreign=true ;;
        esac
    done <<< "$(printf '%s' "$PATH" | tr ':' '\n')"
    if [ "$found_foreign" = "false" ]; then
        ok "No other-platform binaries in the toolchain, no WSL paths on PATH"
    else
        problems=$((problems + 1))
    fi

    echo ""
    if [ "$problems" -eq 0 ]; then
        ok "Toolchain is correct for this platform — ./build.sh will work."
        echo ""
        return 0
    fi
    err "${problems} problem(s) found."
    if $IS_WINDOWS; then
        echo "    Fix:      build.cmd          (downloads the Windows build-tools)"
        echo "    Then:     build.cmd doctor"
    else
        echo "    Fix:      ./build.sh setup"
        echo "    Or:       $(package_install_hint)"
    fi
    echo ""
    return 1
}

# ---------------------------------------------------------------------------
# Toolchain summary and verification
# ---------------------------------------------------------------------------
print_toolchain() {
    local t p res
    for t in aapt2 zipalign apksigner; do
        if p=$(tool_path "$t"); then
            ok "$t: $p"
        else
            err "$t: not found"
        fi
    done
    if res=$(framework_res_path); then
        ok "resources: $res"
    else
        err "resources: framework-res.apk not found"
    fi
    if command -v java >/dev/null 2>&1; then
        ok "java: $(command -v java)"
    else
        err "java: not found (apksigner needs JDK 17+)"
    fi
}

verify_toolchain() {
    local missing
    missing=$(toolchain_missing)
    if [ -z "$missing" ]; then
        ok "Toolchain ready"
        return 0
    fi
    err "Toolchain is still incomplete — missing: $missing"
    echo ""
    if $IS_WINDOWS; then
        echo "    Fix the message above, then run: build.cmd"
        echo "    Check again:                     build.cmd doctor"
    else
        echo "    Install:       $(package_install_hint)"
        echo "    Or interactive: ./build.sh setup"
        echo "    Check again:    ./build.sh doctor"
    fi
    echo ""
    return 1
}

# ---------------------------------------------------------------------------
# ensure_toolchain <auto|interactive> [force-resources]
# ---------------------------------------------------------------------------
ensure_toolchain() {
    local mode="${1:-auto}" force_res="${2:-}" missing

    missing=$(toolchain_missing)
    if [ -z "$missing" ] && [ -z "$force_res" ]; then
        ok "Toolchain ready"
        return 0
    fi

    echo ""
    info "Toolchain incomplete — missing: ${missing}"

    if [ "$mode" = "auto" ]; then
        if $IS_WINDOWS; then
            # One download covers aapt2/zipalign/apksigner; Java must be there
            # first because the installer checks it before touching anything.
            install_windows_tools || return 1
        else
            # Prefer the distro packages; fall back to a local download that
            # needs no root (aapt2 from Maven + SDK command-line tools).
            install_linux_packages auto || download_manual_tools || true
        fi
        if [ -n "$force_res" ] || ! framework_res_path >/dev/null 2>&1; then
            acquire_framework_res auto "$force_res" || true
        fi
        verify_toolchain
        return $?
    fi

    # Interactive setup ------------------------------------------------------
    echo ""
    echo -e "  ${BOLD}Checking available tools...${NC}"
    echo ""
    check_tool_report() {
        local name="$1" cand kind found=false
        while IFS= read -r cand; do
            [ -n "$cand" ] || continue
            kind=$(classify_binary "$cand")
            if kind_usable "$kind"; then
                ok "$name found: $cand [$(kind_label "$kind")]"
                found=true
                break
            fi
            warn "$name at $cand is a $(kind_label "$kind") — cannot run here, ignoring"
        done <<< "$(tool_candidates "$name")"
        $found
    }
    check_tool_report aapt2 || true
    check_tool_report zipalign || true
    check_tool_report apksigner || true
    command -v java >/dev/null 2>&1 && ok "java found: $(command -v java)" || err "java not found"
    framework_res_path >/dev/null 2>&1 && ok "resources found: $(framework_res_path)" || err "resources not found"

    if [ -z "$(toolchain_missing)" ] && [ -z "$force_res" ]; then
        echo ""
        ok "Nothing to install — everything is already available."
        echo ""
        echo "  Build with: ./build.sh"
        echo ""
        return 0
    fi

    # Tools are fine (only the resource dictionary is missing, or --force was
    # used): no need to reinstall the compiler/signer, just pick resources.
    local missing_tools=false
    for t in aapt2 zipalign apksigner; do
        tool_ready "$t" || missing_tools=true
    done
    command -v java >/dev/null 2>&1 || missing_tools=true
    if ! $missing_tools; then
        acquire_framework_res ask "$force_res" || true
        echo ""
        print_toolchain
        echo ""
        verify_toolchain
        return $?
    fi

    echo ""
    echo -e "  ${BOLD}How should the missing tools be installed?${NC}"
    echo -e "    ${BOLD}[1]${NC} Debian / Ubuntu / Mint        (apt)"
    echo -e "    ${BOLD}[2]${NC} Arch Linux / Manjaro         (pacman)"
    echo -e "    ${BOLD}[3]${NC} Android / Termux             (pkg)"
    echo -e "    ${BOLD}[4]${NC} Manual download into tools/  (no root)"
    if $IS_WINDOWS; then
        echo -e "    ${BOLD}[5]${NC} Windows build-tools          ${GREEN}<-- use this${NC}"
    else
        echo -e "    ${BOLD}[5]${NC} Windows build-tools          (only for Git Bash on Windows)"
    fi
    echo ""
    ask "  Selection [1/2/3/4/5]: " "$($IS_WINDOWS && echo 5 || echo 4)"

    case "$REPLY" in
        1)
            if $IS_WINDOWS; then
                warn "apt is not available on Windows. Choose [5]."
            elif install_linux_packages interactive; then
                acquire_framework_res ask || true
            fi
            ;;
        2)
            if $IS_WINDOWS; then
                warn "pacman is not available on Windows. Choose [5]."
            elif install_linux_packages interactive; then
                acquire_framework_res ask || true
            fi
            ;;
        3)
            if $IS_WINDOWS; then
                warn "pkg is not available on Windows. Choose [5]."
            elif install_linux_packages interactive; then
                acquire_framework_res ask || true
            fi
            ;;
        4)
            download_manual_tools && { acquire_framework_res ask || true; }
            ;;
        5)
            if $IS_WINDOWS; then
                install_windows_tools || return 1
                acquire_framework_res ask || true
            else
                warn "This option installs the Windows .exe toolchain."
                warn "Pick the option that matches this OS instead."
            fi
            ;;
        *)
            info "Nothing installed."
            ;;
    esac

    echo ""
    echo -e "  ${BOLD}Result${NC}"
    print_toolchain
    echo ""
    verify_toolchain
}
